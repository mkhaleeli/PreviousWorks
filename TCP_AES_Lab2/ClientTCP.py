from socket import *
from cryptography.hazmat.primitives.ciphers import (Cipher, algorithms, modes)
from cryptography.hazmat.backends import default_backend
from cryptography.exceptions import InvalidTag
import secrets 
import ast #For String to List Conversions

serverName = '127.0.0.1' # An address to tell a computer to communicate with itself (local communication)

serverPort = 12000 #Port Number for where server listens for incoming data (from TCPServer)

clientSocket = socket(AF_INET, SOCK_STREAM) 

clientSocket.connect((serverName,serverPort)) #Establishes a connection with defined server name and port

m = input('Input Message: ') #String input from user

header =  b"Header Info: Source = 'Client', Destination = 'Server', mode = 'GCM', ..."

# Symmetric Key Exchange: Symmetric Encrpytion to Exchange a new key


'''Client Activity: k is a symmetric key for key-exchange 
1. Take Plaintext Message (m) from user and encrypt is using an AES-256 key (assuming an existing key, k) and then send the ciphertext over the socket to the server. 
Note: The key may be generated by the client program, stored into a file, and then shared with the server program
    - Encrypt Message using AES-256 key
    - Send Encrypted Message as a File
'''

#Existing initial key (k1): randomly generated to a size of 32 bytes suitable for a AES-256 key
k = secrets.token_bytes(32) 

#AES-256 Encryption using GCM (avoids padding and avoids sequential block encryption reliance, using a built in counter instead for any message size)  
def encrypt(key, message, aa):
    data = message.encode('utf-8')
    
    #Allows encryption of plaintext into different ciphertext, even if the same message
    iv = secrets.token_bytes(16)
    
    print(f"Client: Encrypting .... data: {message}, iv: {iv.hex()} \n")
    cipher = Cipher(
        algorithms.AES(key),
        modes.GCM(iv),
        backend=default_backend())
        
    #Encrypts using Cipher Template
    encryptor = cipher.encryptor()
    
    #Authenticates Associated Data
    encryptor.authenticate_additional_data(aa)
    
    #Creates whole Ciphertext (With additional finalization of encryption to avoid reuse & flush remaining buffered data)
    ciphertext = encryptor.update(data) + encryptor.finalize()
    
    #Authentication Tag (AEAD)
    tag = encryptor.tag
    
    return key, ciphertext, iv, aa, tag 


# Encrypted Message using key, sent with key, iv, ciphertext, and associated data
k, e_m, iv, header, tag = encrypt(k, m, header)

#List to write into file
list_of_values = [k, e_m, iv, header, tag]

#Convert from list to string
def list_to_String(mylist):
    result = ",".join(map(str, mylist))
    return result

client_file = list_to_String(list_of_values)

print("Client File: ", client_file, '\n')

#Send Encrypted Message to Server
with open('data.txt', 'w') as file:
    file.write(client_file)

# Send Encrypted Message as a userfile
clientSocket.send(client_file.encode()) #Sends message in bytes to the server
print("Client: Encrypted Message Sent \n")

'''Client Activity
4. Once the client receives the encrypted dm and the encrypted nk, first decrypt the encrypted nk to get the new symmetric key (nk).
   Then use the new symmetric key (nk) to decrypt the encrypted dm.
   The outcome of decrypting dm should be compared with the original plaintext message (m) that was sent to the server.
   Print the appropriate message depending on if the plaintexts match or not.
   - Decrypt new symmetric key nk with k
   - Use nk to decrypt encrypted dm
   - Compare m to dm
'''

#AES-256 Decryption using GCM with new symmetric key 
def decrypt(newkey, ciphertext, iv, aa, tag):
    
    print(f"Client: Decrypting .... ciphertext: {ciphertext.hex()}, iv: {iv.hex()} \n")   
    
    #Key Decrypter
    key_cipher = Cipher(
        algorithms.AES(k),
        modes.GCM(iv, tag),
        backend=default_backend())
    
    #Decrypts Key
    key_decryptor = key_cipher.decryptor()
    
    #Decrypt nk with k
    nk = key_decryptor.update(newkey)
    
    #Message Decryptor
    cipher = Cipher(
        algorithms.AES(nk),
        modes.GCM(iv, tag),
        backend=default_backend())
    
    #Decrypts Message
    decryptor = cipher.decryptor()
    
    #Decrypts Associated Data
    decryptor.authenticate_additional_data(aa)
    
    #Decrypts Ciphertext and return Plaintext + key
    try:
        plaintext = decryptor.update(ciphertext) + decryptor.finalize()
        message = plaintext.decode('utf-8')
        return message
    
    #Checks Tag Authenication
    except InvalidTag:
        print("Client: Decryption Failed, Invalid Authenication Tag", tag , '\n')
        

server_file = clientSocket.recv(1024) #Receives the modified message once returned
print("Client: Received Modified Message \n" )

#Read message from the Server
with open('data.txt','r') as file:
    server_file = file.read()

print("Server File: ", server_file, '\n')

#Convert string back into a list of values
def string_to_List(myString):
    result = ast.literal_eval(myString)
    return result
        
list_of_values = string_to_List(server_file)

e_nk, e_m2, iv, aa, tag = list_of_values #List unpacking

#Decrypt encrypted message from Server
dm2 = decrypt(e_nk, e_m2, iv, aa, tag)

#Compare m to dm2
if(m.lower() == dm2.lower()):
   print("Same Message File! \n")
   print("Decoded Message From Server:", dm2, "\n") #Decodes message from bytes back into string form from server

else:
    print("Client: Not The Same Message \n")
    print("Decoded Message From Server: ", dm2)

clientSocket.close() #client ends connection